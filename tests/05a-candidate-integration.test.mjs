import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createMainV2Inventory} from '../src/main-v2-inventory.js';
import {createSaveV2,prepareSecondsV2ToV3,createSaveV3,decodeSaveV3} from '../dist/engine/v2.js';
const opts={worldSeed:'05a-candidate',generatedWorld:true,worldPersistence03E:true,progression04A:true,resources05A:true,preferences:{getItem:()=>null,setItem:()=>{}}};
const make=()=>createMainV2Inventory([{id:'test:starter',name:'시험',group:'재료',qty:1,tags:[]}],opts);
const slot={slotId:'candidate-a',worldId:'world',kind:'manual',label:'test',savedAt:'2026-10-24T00:00:00Z',revision:0};
test('candidate discovery and harvest go through authoritative dispatcher, inventory, compendium and v3 save',()=>{
 const game=make(),id='site05a:blueberry:숲';
 assert.equal(game.dispatch('resource.candidate.work',{nodeId:id}).accepted,false);
 assert.equal(game.dispatch('world.travel',{region:'숲'}).accepted,true);
 const start=game.current().clock.elapsedUnits;
 assert.equal(game.dispatch('resource.candidate.discover',{nodeId:id}).accepted,true);
 assert.equal(game.current().clock.elapsedUnits-start,600);
 const before=game.current();
 const work=game.dispatch('resource.candidate.work',{nodeId:id});
 assert.equal(work.accepted,true,JSON.stringify(work));
 const after=game.current();
 assert.equal(after.clock.elapsedUnits-before.clock.elapsedUnits,60);
 assert.equal(after.world.runtime.resource05A.candidateSites[id].remaining,3);
 assert.equal(after.itemWorld.items.find(x=>x.definitionId==='item05a:blueberry').quantity,1);
 assert.deepEqual(after.world.runtime.resource05A.compendium.sourceIds,['source05a:blueberry']);
 const v2=createSaveV2(after,slot,'test',game.registry);
 const converted=prepareSecondsV2ToV3(v2,game.registry);assert.equal(converted.ok,true);
 const v3=createSaveV3(converted.state,slot,'test',game.registry);
 assert.equal(decodeSaveV3(v3,game.registry).ok,true);
 const restored=make();restored.applyApprovedSave(v3);
 assert.deepEqual(restored.current().world.runtime.resource05A,after.world.runtime.resource05A);
 assert.deepEqual(restored.current().itemWorld,after.itemWorld);
});
test('candidate invalid region and duplicate discovery do not spend time',()=>{
 const g=make(),id='site05a:quartz:광산';
 const start=g.current();
 assert.equal(g.dispatch('resource.candidate.discover',{nodeId:id}).accepted,false);
 assert.equal(g.current().clock.elapsedUnits,start.clock.elapsedUnits);
 g.dispatch('world.travel',{region:'광산'});
 assert.equal(g.dispatch('resource.candidate.discover',{nodeId:id}).accepted,true);
 const before=g.current();
 assert.equal(g.dispatch('resource.candidate.discover',{nodeId:id}).accepted,false);
 assert.equal(g.current().clock.elapsedUnits,before.clock.elapsedUnits);
});
